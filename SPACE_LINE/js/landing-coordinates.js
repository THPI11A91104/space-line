export function coordinateText(slotId) {
  const index = Number(String(slotId).split("-").at(-1)) - 1;
  const { lat, lon } = points[index] ?? points[0];
  const latitude = Math.abs(lat).toFixed(3) + "° " + (lat < 0 ? "S" : "N");
  const longitude = Math.abs(lon).toFixed(3) + "° " + (lon < 0 ? "W" : "E");
  return latitude + " / " + longitude;
}
